def sumar(a,b):
    print(f"El resultado de la suma es: {a+b}")
    return a+b

def restar(a,b):
    print(f"El resultado de la resta es: {a-b}")
    return a-b

def multiplicar(a,b):
    print(f"El resultado de la multiplicacion es: {a*b}")
    return a*b

def dividir(a,b):
    print(f"El resultado de la division es: {a/b}")
    return a/b